def file_meta(path: Path):
    """파일명에서 (방이름, YYYYMMDD) 를 뽑는다. 규칙 두 가지 모두 지원."""
    stem = path.stem
    m = RE_NAME_A.match(stem)
    if m:
        return m.group(3).strip(), m.group(1)
    m = RE_NAME_B.match(stem)
    if m:
        return m.group(1).strip(), m.group(2)
    return stem, None


def read_text(path: Path) -> str:
    """.txt 는 CP949(실측), .rtf 는 CP949 + rtf_to_text."""
    raw = path.read_bytes()
    for enc in ("cp949", "utf-8-sig", "utf-8"):
        try:
            text = raw.decode(enc)
            break
        except UnicodeDecodeError:
            continue
    else:
        text = raw.decode("cp949", errors="replace")
    if path.suffix.lower() == ".rtf":
        text = rtf_to_text(text, encoding="cp949", errors="ignore")
    return text


def split_messages(text: str):
    """1차 분리. 헤더 없는 줄은 직전 발언 본문에 이어 붙인다."""
    out, cur = [], None
    for line in text.splitlines():
        line = line.rstrip()
        if not line:
            continue
        m = RE_HEADER.match(line)
        if m:
            if cur:
                out.append(cur)
            sender = m.group(1).strip()
            if RE_SYSTEM.search(sender) or len(sender) > 30:
                cur = None
                continue
            cur = [sender, m.group(2), m.group(3).strip()]
        elif cur is not None:
            if RE_SYSTEM.search(line):
                out.append(cur)
                cur = None
                continue
            cur[2] = (cur[2] + " " + line.strip()).strip()
    if cur:
        out.append(cur)
    return out


