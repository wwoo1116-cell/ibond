# 규약: N ≥ 1 이면 전(=0.01원), N < 1 이면 원. 원으로 통일해 FeeWon 에 담는다.
# ⚠ '수' 는 요일(수요일) 표기와 충돌한다 — 숫자가 바로 따르고 뒤가 닫는
#   문맥(괄호·구분자)일 때만 받는다.
# ⚠ `(수0,1)` 처럼 쉼표를 소수점으로 쓴 행이 57건 있다(메리츠 한 데스크).
#   쉼표 소수점을 받고, 0 은 값이 아니라 오독이므로 버린다.
RE_FEE_AMT = re.compile(
    r'(?:총\s*)?수(?:수료|수)?\s*(\d{1,3}(?:[.,]\d{1,2})?)\s*(전|원)?\s*[)\]/,]')


def fee_won(core):
    """수수료 표기 -> 원. 없으면 None."""
    m = RE_FEE_AMT.search(core)
    if not m:
        return None
    v = float(m.group(1).replace(',', '.'))
    unit = m.group(2)
    if v == 0:
        return None
    if unit == '전':
        return v / 100.0
    if unit == '원':
        return v
    return v / 100.0 if v >= 1 else v


