RE_AMOUNT_BARE = re.compile(
    r'(?:팔자|사자|매도|매수)\s*(?<![\d.,])(\d{1,4})'
    r'(?!\s*[*xX×])'
    r'(?![\d.,\-%/]|\s*(?:억|장|매|년|월|일|차|호|기|번|만|bp|비피|빕|삡|원|BP))')
BARE_SKIP_SECTOR = {"CD", "CP/전단"}
LOT_DEFAULT = 100.0        # 1계약 = 100억


def bare_amount(text, sector=None):
    """동사 뒤 단위 없는 맨숫자 -> 실효 수량(억). 못 읽으면 None.
    ★[OWNER 2026-09-03] 「팔자 2 는 아마 200억, 팔자 100 은 100억, 팔자 30 은 30억」
      한 자리는 «계약 수»(×100억), 두 자리부터는 억이다.
      근거: 2억·5억은 문면에 «2억» 으로 적힌다(전 기간 802건). 한 자리 맨숫자는
      13행뿐이라 억으로 읽을 이유가 없다.
    ★이 함수가 규칙의 유일한 출처다 — backfill_amounteff.py 도 이걸 부른다.
      (한때 백필이 규칙을 따로 구현해 새 규칙이 안 먹었다.)"""
    if sector in BARE_SKIP_SECTOR:
        return None
    m = RE_AMOUNT_BARE.search(str(text))
    if not m:
        return None
    try:
        v = float(m.group(1))
    except (TypeError, ValueError):
        return None
    if 1 <= v <= 9:
        return v * LOT_DEFAULT
    if v % 10 == 0 and 10 <= v <= 1000:
        return v
    return None

