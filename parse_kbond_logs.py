def _pair_ok(a: str, b: str) -> bool:
    """두 수가 «0.5bp 떨어진 인접 두 칸» 인가.

    ★원장 전수(2026-09-04): 짝 꼴 473,373행 중 간격이 정확히 +5 인 것이 98.9%,
      앞<뒤가 100.0% 다. 나머지 0.5% 는 −995 인데 이것은 핸들 넘김이다
      («995 00-» = 4.995 / 5.000). 둘을 받고 나머지는 짝이 아니다.
    """
    d = _pad3(b) - _pad3(a)
    return d == 5 or d == -995


def _pad3(tok: str) -> int:
    """«63» -> 630 · «625» -> 625. 두 수를 같은 격자에서 비교하기 위해."""
    return int(tok) * 10 if len(tok) == 2 else int(tok)

