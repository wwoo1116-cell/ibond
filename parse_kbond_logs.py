def main():
    t0 = time.time()
    print(f"[1/5] 대상 수집 : {SRC_DIR}")
    if not SRC_DIR.is_dir():
        sys.exit(f"[FATAL] 경로 없음: {SRC_DIR}")

    files = [p for p in SRC_DIR.iterdir()
             if p.suffix.lower() in EXTS and any(r in p.name for r in ROOMS)]
    print(f"      파일 {len(files):,}개 "
          f"({sum(p.stat().st_size for p in files) / 2**20:,.0f} MB)")

    groups = {}
    unnamed = 0
    for p in files:
        room, date = file_meta(p)
        room = next((r for r in ROOMS if r in room), room)
        if date is None:
            unnamed += 1
            continue
        groups.setdefault((room, date), []).append(str(p))
    print(f"      (방,날짜) 그룹 {len(groups):,}개, 날짜 미상 {unnamed}개")
    for r in ROOMS:
        ds = sorted(d for rm, d in groups if rm == r)
        print(f"      {r}: {len(ds):,}일  {ds[0]} ~ {ds[-1]}")

    print(f"[2/5] 파싱 (프로세스 {WORKERS}개)")
    tasks = [(r, d, ps) for (r, d), ps in sorted(groups.items(), key=lambda kv: kv[0][1])]

    # T16: 옛 코드는 최종 산출물을 «먼저 지우고» 새로 흘려 썼다. 부트스트랩은
    # 두 시간 가까이 걸리므로 도중에 죽으면 새 것도 없고 직전 것도 없다.
    # 임시 경로에 다 쓴 뒤에만 갈아끼운다.
    TMP_CSV = OUT_CSV.with_suffix(".csv.tmp")
    TMP_PARQUET = OUT_PARQUET.with_suffix(".parquet.tmp")
    for _p in (TMP_CSV, TMP_PARQUET):
        _p.unlink(missing_ok=True)

    # 700만 행을 한 DataFrame 으로 들고 있으면 10GB 를 넘는다.
    # 그룹 단위 DataFrame 으로 만들어 CSV/Parquet 에 흘려보내고,
    # 통계는 증분 카운터로 쌓는다.
    import pyarrow as pa
    import pyarrow.parquet as pq

    # 전부 결측인 컬럼은 그룹마다 null 타입으로 추론돼 Parquet 스키마가
    # 흔들린다(첫 실행 실패 원인). 스키마를 못 박고 매 그룹 cast 한다.

    header_written = False
    total_raw = total_noise = total_rows = 0
    null_counts = Counter()
    dist = {c: Counter() for c in ["Position", "PositionSource", "Sector", "MsgType", "Room"]}
    errors, sample_rows = [], []
    writer, done = None, 0

    with ProcessPoolExecutor(max_workers=WORKERS) as ex:
        for room, date, n_raw, n_noise, rows in ex.map(parse_group, tasks, chunksize=4):
            done += 1
            errors += [r["_error"] for r in rows if "_error" in r]
            rows = [r for r in rows if "_error" not in r]
            if rows:
                df = pd.DataFrame(rows).reindex(columns=COLUMNS)
                df["Timestamp"] = pd.to_datetime(
                    df["Date"] + " " + df["Time"], format="%Y%m%d %H:%M:%S", errors="coerce")
                df["Date"] = pd.to_datetime(df["Date"], format="%Y%m%d", errors="coerce")
                df["OddLot"] = df["OddLot"].astype("boolean")
                df["AmountImplied"] = df["AmountImplied"].astype("boolean")
                df["IsInquiry"] = df["IsInquiry"].astype("boolean")

                df.to_csv(TMP_CSV, mode="a", header=not header_written,
                          index=False, encoding="utf-8-sig")
                header_written = True

                table = pa.Table.from_pandas(df, preserve_index=False)
                table = table.cast(PA_SCHEMA)
                if writer is None:
                    writer = pq.ParquetWriter(TMP_PARQUET, PA_SCHEMA,
                                              compression="zstd")
                writer.write_table(table)

                for c in COLUMNS:
                    null_counts[c] += int(df[c].isna().sum())
                for c, ctr in dist.items():
                    ctr.update(df[c].fillna("(없음)").astype(str).value_counts().to_dict())
                total_rows += len(df)
                if len(sample_rows) < 12:
                    hit = df[df["Position"].notna() & df["Amount"].notna()]
                    if len(hit):
                        sample_rows.append(hit.head(3))
            total_raw += n_raw
            total_noise += n_noise
            if done % 100 == 0 or done == len(tasks):
                print(f"      {done:,}/{len(tasks):,} 그룹  누적 {total_rows:,}행  "
                      f"{time.time() - t0:,.0f}s")
    if writer is not None:
        writer.close()

    # 여기까지 왔으면 두 산출물이 온전하다. 이때만 갈아끼운다.
    os.replace(TMP_PARQUET, OUT_PARQUET)
    os.replace(TMP_CSV, OUT_CSV)

    print(f"[3/5] CSV  : {OUT_CSV} ({OUT_CSV.stat().st_size / 2**20:,.0f} MB)")
    print(f"[4/5] Parquet : {OUT_PARQUET} "
          f"({OUT_PARQUET.stat().st_size / 2**20:,.0f} MB)")

    # ------------------------------------------------------------ 리포트
    print("\n" + "=" * 74)
    print("파싱 리포트")
    print("=" * 74)
    print(f"  대상 파일          {len(files):,}")
    print(f"  1차 분리 발언      {total_raw:,}")
    print(f"  빈/온점 제외       {total_noise:,}")
    print(f"  중복 제거 후 행수  {total_rows:,}"
          f"   (중복률 {100 * (1 - total_rows / max(total_raw - total_noise, 1)):.1f}%)")
    print(f"  읽기 실패 파일     {len(errors)}")
    for e in errors[:5]:
        print(f"      {e}")
    print(f"  소요               {time.time() - t0:,.0f}초")

    print("\n  결측치 비율")
    for c in COLUMNS:
        n = null_counts[c]
        bar = "#" * int(30 * n / max(total_rows, 1))
        print(f"    {c:<15} {100 * n / max(total_rows, 1):6.2f}%  {bar}")

    for name, ctr in dist.items():
        print(f"\n  {name} 분포")
        for k, v in ctr.most_common(8):
            print(f"    {k:<14} {v:>10,}  ({100 * v / max(total_rows, 1):5.2f}%)")

    if sample_rows:
        print("\n  샘플")
        cols = ["Date", "Time", "Room", "Sender", "Position", "PositionSource",
                "Sector", "BondCode", "BondName", "MPYield", "SpreadValue",
                "SpreadUnit", "Amount"]
        smp = pd.concat(sample_rows, ignore_index=True).head(10)
        smp["Date"] = smp["Date"].dt.strftime("%Y-%m-%d")
        with pd.option_context("display.width", 250, "display.max_columns", 40):
            print(smp[cols].to_string(index=False))

    print("\n[5/5] 완료")


if __name__ == "__main__":
    main()
