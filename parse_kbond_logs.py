# Sender 도 같다 — '이정훈' 과 '이정훈.' 이 동일인이다(525,084행).
RE_KEY_DIGITS = re.compile(r'\d')
RE_SENDER_STRIP = re.compile(r'\([^)]*\)|[.\s_*·]+$|\s+')
RE_SENDER_SUFFIX = re.compile(r'(?:im|ds|bgc|trad|prebon)$', re.IGNORECASE)


def broker_key(broker):
    """브로커 문자열 -> 전화번호 정규화 키. 표시 이름 흔들림을 흡수한다."""
    if not broker:
        return None
    m = RE_PHONE.search(broker)
    if not m:
        return None
    d = "".join(RE_KEY_DIGITS.findall(m.group(0)))
    if d.startswith("02") and len(d) > 8:
        d = d[2:]
    return d or None


def sender_key(sender):
    """대화명 -> 동일인 키. 말미 마침표·회사접사·괄호구를 벗긴다."""
    if not sender:
        return None
    t = RE_SENDER_STRIP.sub("", str(sender))
    t = RE_SENDER_SUFFIX.sub("", t)
    return t.lower() or None


