def test_통안을_반기로_놓으면_크게_틀린다():
    """★규약이 테너가 아니라 «발행체 × 이자종류» 라는 것을 수로 못 박는다.

    이 시험이 지키는 것은 «맞는 값» 이 아니라 «틀린 값이 얼마나 틀리나» 다.
    m 을 잘못 주고도 0.01원 안에 들어오면 위 시험들이 m 을 안 재고 있다는 뜻이다.
    """
    sp2 = _spec("통안2611-01", 2.540, date(2026, 11, 9), 2)     # 일부러 반기
    sp4 = _spec("통안2611-01", 2.540, date(2026, 11, 9), 4)     # 정답
    assert abs(KP.price(sp4, 3.145, T0) - 10023.23) <= TOL
    assert KP.price(sp2, 3.145, T0) - 10023.23 > 50.0            # 실측 +63.26원


