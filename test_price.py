def test_이표일은_만기에서_역산한다():
    """국고24-4(만기 2027-06-10, m=2) -> 2026-12-10, 2027-06-10 두 장."""
    cfs, prev = KP.coupon_dates(date(2027, 6, 10), T0, 2)
    assert cfs == [date(2026, 12, 10), date(2027, 6, 10)]
    assert prev == date(2026, 6, 10)


def test_1원은_1bp가_아니다():
    """★장기물에서 «1원 ≈ 1bp» 어림을 쓰면 자릿수가 틀린다.

    26-2(만기 2056-03-10)는 1원이 0.07bp 도 안 된다.
    """
    단기 = _spec("25-4", 2.250, date(2028, 6, 10), 2)
    장기 = _spec("26-2", 3.500, date(2056, 3, 10), 2)
    r단, r장 = KP.bp_per_won(단기, 4.00, T0), KP.bp_per_won(장기, 4.35, T0)
    assert 0.55 < r단 < 0.70
    assert r장 < 0.10
    assert r단 / r장 > 8                       # 같은 1원이 여덟 배 넘게 다르다


