/**
 * 차트의 «치수» — 라이브러리를 **안 물고** 읽을 수 있어야 하는 수들. [2026-09-28]
 *
 * ── 왜 파일이 따로인가 ────────────────────────────────────────────────────
 * 이 수들은 캔버스 차트에서 나왔지만, 그 옆에 서는 **SVG 차트**(잔존×YTM 산점도)도
 * 같은 수를 써야 한다 — 두 그림의 오른쪽 축 폭이 다르면 한 화면에서 플롯의 끝이
 * 어긋난다.
 *
 * 그런데 `useLwChart.ts` 는 `lightweight-charts` 를 모듈 꼭대기에서 불러온다.
 * 거기서 상수 하나를 가져오면 **라이브러리 전체가 그 파일의 번들로 딸려 온다** —
 * 실측 2026-09-28: 커브가 `CROSSHAIR_LABEL_MIN_W` 하나를 임포트하자 메인 첫 화면의
 * JS 가 787KB → 964KB 로 늘었다(지연 로드가 통째로 무효가 됐다). 커브는 크레딧 탭의
 * 정적 임포트라 본체 번들에 있고, 그래서 라이브러리도 본체로 따라 들어왔다.
 *
 * 수를 들고 있는 파일이 아무것도 안 물면 그런 일이 없다.
 */

