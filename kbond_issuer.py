def strip_head(body):
    """본문 머리의 날짜·요일·태그·글머리표를 «더 못 걷을 때까지» 걷는다."""
    s = str(body)
    for _ in range(8):                       # 실측 최대 4겹. 8이면 넉넉하고 안 돈다.
        before = s
        for rx in _HEAD_STRIP:
            s = rx.sub("", s, count=1)
        if s == before:
            break
    return s


