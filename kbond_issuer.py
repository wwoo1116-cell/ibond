# ★캐시 — `split_name` 은 이름 길이만큼 사전을 두드린다(14자면 13번, 각각 정규화 1회).
#   원장 826만행에 그대로 걸면 수천만 번이 되는데, 서로 다른 머리말은 3만종뿐이다.
@lru_cache(maxsize=200_000)
def split_name(name):
    """머리말과 꼬리를 가른다.

        '산금FRN725-2팔자' -> ('산금', (('drop','팔자'), ('series','725-2'),
                                        ('structure','FRN')))

    ⚠ 꼬리는 dict 가 아니라 **정렬된 튜플**로 돌려준다 — `lru_cache` 가 걸려 있어
      돌려준 것을 하류가 고치면 캐시가 오염된다. 쓸 때 `dict(...)` 로 받는다.

    사전에 있는 **가장 긴 머리말**을 찾고, 남은 꼬리가 회차·상품구조·동사로
    설명될 때에만 자른다. 설명이 안 되면 자르지 않는다(머리말 = 원문).
    """
    s = str(name).strip()
    for cut in range(len(s), 1, -1):
        if _norm(s[:cut]) not in RESOLVE:
            continue
        head, tail, got, ok = s[:cut], s[cut:].strip(), {}, True
        while tail:
            # ★[2026-09-10] 뜻이 바뀌는 꼬리는 아예 안 자른다. 다른 어휘보다 먼저 본다.
            if any(tail.startswith(t) for t in KEEP_TAIL):
                ok = False
                break
            # ⚠ 어휘 «합집합» 에서 가장 긴 것을 문다. 목록 순서로 가르면 뜻이 바뀐다 —
            #   DROP 을 먼저 보면 「일반」이 요일 「일」에 물려 「반」이 남고,
            #   STRUCTURE 를 먼저 보면 「사자」가 홑글자 「사」에 물려 쪼개진다.
            #   최장일치는 둘 다 옳게 문다(사자 2 > 사 1 · 일반 2 > 일 1).
            hit = next((t for t in _VOCAB if tail.startswith(t)), None)
            if hit:
                got.setdefault("drop" if hit in DROP else "structure", hit)
                tail = tail[len(hit):].strip()
                continue
            m = RE_RATING.match(tail)
            if m:
                got.setdefault("rating", m.group(0))
                tail = tail[m.end():].strip()
                continue
            m = RE_SERIES.match(tail)
            if m:
                got.setdefault("series", m.group(0))
                tail = tail[m.end():].strip()
                continue
            ok = False
            break
        if ok:
            return head, tuple(sorted(got.items()))
    return s, ()


@lru_cache(maxsize=200_000)
def canon_issuer(name):
    """발행체명 -> (정본, 출처).

    출처
      power5    발전 5사로 확정 — 변별 토큰 + 발전 어간
      master    원장(cclass·issuer·종목명 머리말)이 말한 것
      near      음차·접미 절단으로 원장 이름에 붙인 것 (kbond_issuer_near)
      mp-test   민평 검정이 통과시킨 것
      owner     사람이 판정한 것
      ambiguous 한 이름에 발전사가 둘 (실측 0건이나 규칙상 열어 둔다)
      raw       못 접었다. 원문을 그대로 돌려준다.

    ⚠ 못 접었을 때 None 이 아니라 **원문**을 돌려준다. 하류가 IssuerCanon 만 보고도
      항상 이름을 얻게 하려는 것이다. 접었는지는 출처로 가린다.
    """
    if not name:
        return None, None
    s = str(name).strip()
    if not s:
        return None, None
    hits = {POWER5[m.group(1)] for m in RE_POWER5.finditer(s)}
    if len(hits) == 1:
        return hits.pop(), "power5"
    if len(hits) > 1:
        return s, "ambiguous"
    head, _part = split_name(s)
    k = _norm(head)
    if k in RESOLVE:
        return RESOLVE[k], SOURCE[k]
    # ★[2026-09-09 2차] 사전에 없는 발행체 — 원장에 아예 없는 것들이다(고려아연은 CP,
    #   SK에코플랜트·파주에너지·사모 유동화 SPC 등). 접지 않는 게 맞다. 다만 회차까지
    #   붙은 채로 두면 «고려아연123-1» 과 «고려아연» 이 서로 다른 발행체가 된다.
    #   `split_name` 은 머리말이 사전에 있을 때만 자르므로 여기까지 온다.
    #   그래서 예전 규칙(숫자 회차만)을 안전망으로 되살린다 — 모양이 확실한 것만 뗀다.
    bare = _RE_TAIL_NUM.sub("", s).strip()
    return (bare if len(bare) >= 2 else s), "raw"


@lru_cache(maxsize=200_000)
def canon_label(name):
    """표시용 이름 — 머리말만 정본으로 갈고 회차·상품구조는 뒤에 살린다.

        '서부발전60-1'   -> '한국서부발전60-1'
        '산금채EB5'      -> '한국산업은행EB5'
        '산금팔자'        -> '한국산업은행'       (동사는 이름이 아니다)
        '산금FRN'        -> '한국산업은행FRN'     (구조는 값이 갈리므로 남긴다)
        '아이에스동서41-1' -> '아이에스동서41-1'   (안 접힌다)

    라이브 화면과 배치 표가 같은 라벨을 쓰게 하려고 여기 둔다. 따로 구현하면
    검증이 자기 구현을 검증하게 된다(kbond_live 의 다리 분할기와 같은 이유).
    """
    if not name:
        return name
    s = str(name).strip()
    canon, how = canon_issuer(s)
    if how in (None, "raw", "ambiguous"):
        return s
    if how == "power5":
        m = _RE_TAIL_NUM.search(s)
        return canon + (m.group(0).strip() if m else "")
    part = dict(split_name(s)[1])
    return canon + (part.get("structure") or "") + (part.get("series") or "")
