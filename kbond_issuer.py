def canon_issuer(name):
    """발행체명 -> (정본, 출처).

    출처
      power5     발전 5사로 확정 — 변별 토큰 + 발전 어간
      alias      민평 검정을 통과한 별칭표로 접음(101쌍)
      ambiguous  한 이름에 발전사가 둘 (실측 0건이나 규칙상 열어 둔다)
      raw        접지 않았다. 원문을 그대로 돌려준다.

    ⚠ 못 접었을 때 None 이 아니라 **원문**을 돌려준다. 하류가 IssuerCanon 만
      보고도 항상 이름을 얻게 하려는 것이다. 접었는지는 IssuerSource 로 가린다.
    """
    if not name:
        return None, None
    s = RE_TAIL_SERIES.sub("", str(name).strip())
    if not s:
        return None, None
    hits = {POWER5[m.group(1)] for m in RE_POWER5.finditer(s)}
    if len(hits) == 1:
        return hits.pop(), "power5"
    if len(hits) > 1:
        return s, "ambiguous"
    if s in ALIAS:
        return ALIAS[s], "alias"
    return s, "raw"


def canon_label(name):
    """표시용 이름 — 머리말만 정본으로 갈고 회차는 그대로 둔다.

        '서부발전60-1' -> '한국서부발전60-1'
        '아이에스동서41-1' -> '아이에스동서41-1'  (안 접힌다)

    라이브 화면과 배치 표가 같은 라벨을 쓰게 하려고 여기 둔다. 따로 구현하면
    검증이 자기 구현을 검증하게 된다(`kbond_live` 의 다리 분할기와 같은 이유).
    """
    if not name:
        return name
    s = str(name)
    canon, how = canon_issuer(s)
    if how != "power5":
        return s
    m = RE_TAIL_SERIES.search(s)
    return canon + (m.group(0).strip() if m else "")
